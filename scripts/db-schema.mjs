import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Builds supabase/schema.sql from supabase/migrations.
 *
 * schema.sql used to be the only source of truth, edited by hand and pasted into
 * the SQL editor, which is how production drifted from the repo. The migrations
 * directory is now canonical; this script regenerates the single-file installer
 * so fresh projects (and anyone who prefers one paste) still have one.
 *
 *   node scripts/db-schema.mjs          # write supabase/schema.sql
 *   node scripts/db-schema.mjs --check  # fail if it is out of date
 */

const root = process.cwd();
const migrationsDir = join(root, 'supabase', 'migrations');
const outputPath = join(root, 'supabase', 'schema.sql');

const files = readdirSync(migrationsDir)
  .filter((name) => name.endsWith('.sql'))
  .sort();

if (files.length === 0) {
  console.error('No migrations found in supabase/migrations.');
  process.exit(1);
}

const header = [
  '-- Study Hall Supabase schema (generated file — do not edit by hand).',
  '--',
  '-- Generated by `bun run db:schema` from supabase/migrations/*.sql.',
  '-- Apply migrations with `bun run db:migrate`, or paste this file into the',
  '-- Supabase SQL editor for a fresh project. Every statement is idempotent.',
  '--',
  '-- Migrations included:',
  ...files.map((name) => `--   ${name}`),
  '',
  '',
].join('\n');

const body = files
  .map((name) => `-- >>> ${name}\n\n${readFileSync(join(migrationsDir, name), 'utf8').trimEnd()}\n`)
  .join('\n');

const generated = `${header}${body}`;
const check = process.argv.includes('--check');

let current = '';
try {
  current = readFileSync(outputPath, 'utf8');
} catch {
  current = '';
}

const normalise = (value) => value.replace(/\r\n/g, '\n');

if (check) {
  if (normalise(current) === normalise(generated)) {
    console.log('supabase/schema.sql matches supabase/migrations.');
    process.exit(0);
  }
  console.error('supabase/schema.sql is out of date. Run `bun run db:schema`.');
  process.exit(1);
}

writeFileSync(outputPath, generated, 'utf8');
console.log(`Wrote supabase/schema.sql from ${files.length} migration(s).`);
